const iconCache = {};

function iconUrl(key) {
  if (iconCache[key]) return iconCache[key];
  const d = TAB_DISGUISES[key];
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><rect width="108" height="108" rx="24" fill="${d.bg}"/>${d.paths.map(([fill, p]) => `<path fill="${fill}" d="${p}"/>`).join('')}</svg>`;
  return (iconCache[key] = 'data:image/svg+xml,' + encodeURIComponent(svg));
}

function setLink(rel, href) {
  let el = document.querySelector(`link[rel="${rel}"]`);
  if (!el) {
    el = document.createElement('link');
    el.rel = rel;
    document.head.appendChild(el);
  }
  el.type = 'image/svg+xml';
  el.href = href;
}

/** Aplica el disfraz a la pestaña: key = nosotros|calc|notas|reloj|calendario|clima. */
export function applyTabDisguise(key) {
  const d = TAB_DISGUISES[key];
  document.title = d ? d.title : 'Nosotros';
  const href = d ? iconUrl(key) : 'icon.svg';
  setLink('icon', href);
  setLink('apple-touch-icon', href);
}
